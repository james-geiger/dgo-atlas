"""Regenerate the code and JSON Schema derived from the middleware's own schemas.

    uv run python -m dgo_atlas.generate          # rewrite the generated files
    uv run python -m dgo_atlas.generate --check  # exit 1 if any has drifted

These don't depend on DGO, so they are committed. Everything derived from the
authoring template (its pydantic model and editor JSON Schema) depends on the
project's DGO release and is generated at runtime instead (see dgo.py).

This is a developer tool, not a `dgo-atlas` command: it rewrites files inside
the package, which in an implementer's install would be site-packages.
tests/test_generated.py checks that nothing is stale.
"""

from __future__ import annotations

import subprocess
from pathlib import Path
from typing import Annotated

import typer

from .console import fail, say
from .resources import CONFIG_JSON_SCHEMA, CONFIG_SCHEMA, MODELS_DIR, VIEWMODEL

HEADER = "# Generated by `python -m dgo_atlas.generate` from {source}. Do not edit.\n"


def _run(args: list[str]) -> str:
    result = subprocess.run(args, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(f"{' '.join(args[:1])} failed:\n{result.stderr}")
    return result.stdout if result.stdout.endswith("\n") else result.stdout + "\n"


def outputs() -> dict[Path, str]:
    """Every generated file and the content it should have."""
    out: dict[Path, str] = {}
    for schema, module in ((VIEWMODEL, "viewmodel"), (CONFIG_SCHEMA, "config")):
        code = _run(["gen-pydantic", str(schema)])
        out[MODELS_DIR / f"{module}.py"] = HEADER.format(source=f"schema/{schema.name}") + code
    out[CONFIG_JSON_SCHEMA] = _run(["gen-json-schema", "--top-class", "SiteConfig", str(CONFIG_SCHEMA)])
    if EXAMPLE_CONFIG.parent.joinpath("pyproject.toml").exists():  # a source checkout, not an install
        out[EXAMPLE_CONFIG] = example_config()
    return out


